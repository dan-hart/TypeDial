'use strict';

const fs = require('node:fs');
const path = require('node:path');
const config = require('../src/pkjs/config');
const contract = require('../src/pkjs/contract.json');
const profiles = require('../src/pkjs/profiles');
const glyphs = require('../src/pkjs/glyphs.json');
const createColors = require('../src/pkjs/colors');
const createGeometry = require('../src/pkjs/preview-geometry');
const createRenderer = require('../src/pkjs/preview-renderer');
const pointStepper = require('../src/pkjs/point-stepper');

const directory = path.resolve(__dirname, '../playground');
const controller = fs.readFileSync(path.join(directory, 'playground.js'), 'utf8');
const template = fs.readFileSync(path.join(directory, 'template.html'), 'utf8');
const controls = config.flatMap(item => item.items || [item]).filter(item =>
  contract.keys.includes(item.id));
for (const key of contract.keys.filter(key => key !== 'schema')) {
  const item = controls.find(control => control.id === key);
  if (!item || !['select', 'toggle', 'color', 'typedial-point-stepper'].includes(item.type)) {
    throw new Error('Add playground support for the setting: ' + key);
  }
}
const data = JSON.stringify({ controls, contract, profiles, glyphs }).replaceAll('<', '\\u003c');
const script = [
  '  <style>' + pointStepper.style + '</style>',
  '  <script>',
  '  (() => {',
  `    const { controls, contract, profiles, glyphs } = ${data};`,
  `    const colors = (${createColors.toString()})();`,
  `    const geometry = (${createGeometry.toString()})(contract.legacyDigitScales);`,
  `    const createRenderer = ${createRenderer.toString()};`,
  `    const pointStepperTemplate = ${JSON.stringify(pointStepper.template)};`,
  `    const mountPointStepper = ${pointStepper.mount.toString()};`,
  controller.trimEnd(),
  '  })();',
  '  </script>'
].join('\n');
const marker = '  <!-- TYPE_DIAL_PLAYGROUND_SCRIPT -->';
if (!template.includes(marker)) throw new Error('Missing playground script placeholder');
const fontNotices = ['mono', 'next', 'original'].map(variant =>
  fs.readFileSync(path.join(directory, '../licenses', 'atkinson-' + variant + '-OFL.txt'), 'utf8')
    .trimEnd().replace(/[ \t]+$/gm, ''));
const output = '<!-- Generated by node tools/generate-playground.js. Edit the playground sources. -->\n' +
  '<!-- TypeDial source is licensed GPL-3.0-only. See LICENSE in the TypeDial repository. -->\n' +
  '<!-- Atkinson Hyperlegible notices for the bundled font assets\n' + fontNotices.join('\n\n') + '\n-->\n' +
  template.replace(marker, () => script);
const destination = path.join(directory, 'index.html');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    console.error('Playground is out of date. Run make playground.');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(destination, output);
}
